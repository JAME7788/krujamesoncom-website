const uniqueCleanItems = (items: Array<string | undefined>) => {
  const seen = new Set<string>();
  return items
    .map((item) => item?.replace(/\s+/g, ' ').trim())
    .filter((item): item is string => Boolean(item))
    .filter((item) => {
      if (seen.has(item)) return false;
      seen.add(item);
      return true;
    });
};

