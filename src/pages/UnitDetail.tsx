const shouldUseGeneratedSlides = (slides: string[], slideImages?: string[]) => {
  // Do not render bundled third-party slide images; use locally generated lesson slides instead.
  if (slideImages?.length) return true;
  if (slides.length === 0) return true;

  const cleanedSlides = slides.map((slide) => slide.replace(/\s+/g, ' ').trim()).filter(Boolean);
  const combined = cleanedSlides.join(' ');
  if (cleanedSlides.length < 8) return true;

  const incompleteCount = cleanedSlides.filter((slide) => {
    const looksCutOff = /คือ$|คือ\s*$|ดังนั้น$|แผนที่$|แทน$|ได้แก่$|หมายถึง$/.test(slide);
    const tooShortForLesson = slide.length < 90;
    const titleOnly = /^หน่วยการเรียนรู้ที่|^VDO Clip|^กิจกรรม$/i.test(slide);
    return looksCutOff || tooShortForLesson || titleOnly;
  }).length;
  const extractedNoise = /หน่วยการเรียนรู้ที่ ตัวชี้วัด|ซอฟต์แวร์ หรือ สื่อ ที่ใช้ในการ เขียนโปรแกรม ดังนั้น|VDO Clip/.test(combined);
  const hasLearningFlow = /ตัวชี้วัด|เรียนจบ|กิจกรรม|คำถาม|ทบทวน|ภารกิจ|ตรวจสอบ|แก้ไข/.test(combined);

  return extractedNoise || incompleteCount / cleanedSlides.length >= 0.35 || !hasLearningFlow;
};

