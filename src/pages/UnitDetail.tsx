const mergeList = (...lists: Array<string[] | undefined>) => {
  const seen = new Set<string>();
  return lists
    .flatMap((list) => list || [])
    .map((item) => item.replace(/\s+/g, ' ').trim())
    .filter(Boolean)
    .filter((item) => {
      if (seen.has(item)) return false;
      seen.add(item);
      return true;
    });
};

const mergeLessonNotes = (...notes: Array<LessonNotes | undefined>): LessonNotes => ({
  objectives: mergeList(...notes.map((item) => item?.objectives)),
  summary: mergeList(...notes.map((item) => item?.summary)),
  activities: mergeList(...notes.map((item) => item?.activities)),
  checkQuestions: mergeList(...notes.map((item) => item?.checkQuestions)),
  vocabulary: mergeList(...notes.map((item) => item?.vocabulary)),
});

const mergeArticles = (...lists: Array<Article[] | undefined>) => {
  const seen = new Set<string>();
  return lists.flatMap((list) => list || []).filter((item) => {
    const key = `${item.url}|${item.title}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
};

