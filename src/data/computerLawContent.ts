const isPrimary = (key: string) => /^p\d_/.test(key);

/** เติมบทเรียน พ.ร.บ.คอมพิวเตอร์ลงหน่วยความปลอดภัยของแต่ละชั้น (ต่อท้ายของเดิม) */
export const addComputerLawLessons = (extras: Record<string, Record<number, UnitExtras>>) => {
  for (const [key, quiz] of Object.entries(quizByUnit)) {
    const cut = key.lastIndexOf('_');
    const gradeId = key.slice(0, cut);
    const unitNo = Number(key.slice(cut + 1));
    const grade = (extras[gradeId] ??= {});
    const unit = (grade[unitNo] ??= {});
    const existingQuiz = unit.quiz ?? [];
    unit.quiz = [...existingQuiz, ...spreadAnswers(quiz, existingQuiz.length + unitNo)];
    const seen = new Set((unit.articles ?? []).map((a) => a.url));
    unit.articles = [...(unit.articles ?? []), ...lawArticles.filter((a) => !seen.has(a.url))];
    const summary = isPrimary(key) ? primarySummary : secondarySummary;
    unit.lessonNotes = {
      ...unit.lessonNotes,
      summary: [...(unit.lessonNotes?.summary ?? []), ...summary.filter((s) => !unit.lessonNotes?.summary?.includes(s))],
    };
  }
};

export const computerLawUnitKeys = Object.keys(quizByUnit);
export const computerLawQuestionTexts = (key: string) => (quizByUnit[key] ?? []).map((q) => q.q);
