// เนื้อหาบทเรียนสั้น ๆ ที่แสดงก่อนเล่นเกม — แยกภาษาและความลึกตามช่วงวัย
// lower = ป.1-3 (คำง่าย ประโยคสั้น เทียบของใกล้ตัว)
// upper = ป.4-6 (อธิบายหลักการ + ตัวอย่าง)
// middle = ม.1-3 (ศัพท์เทคนิค + เชื่อมโยงการใช้งานจริง)

export interface LessonPoint {
  icon: string;
  text: string;
}

export interface LessonBody {
  /** สรุปแนวคิดใน 1-2 ประโยค */
  concept: string;
  /** 3 ประเด็นหลักที่ต้องรู้ */
  points: LessonPoint[];
  /** ตัวอย่างที่เห็นภาพ */
  example: string;
  /** วิธีเล่นแบบสั้น */
  howTo: string[];
}

export interface GameLesson {
  emoji: string;
  title: string;
  subject: string;
  color: string;
  lower: LessonBody;
  upper: LessonBody;
  middle: LessonBody;
}

export type AgeTier = 'lower' | 'upper' | 'middle';

export const ageTierLabel: Record<AgeTier, string> = {
  lower: 'ป.1-3',
  upper: 'ป.4-6',
  middle: 'ม.1-3',
};

/** เลือกระดับเนื้อหาจากห้องเรียนของนักเรียน */
export const ageTierFromClassroom = (classroom?: string): AgeTier => {
  if (!classroom) return 'upper';
  if (/^ม\./.test(classroom)) return 'middle';
  const n = Number(classroom.replace(/[^0-9]/g, ''));
  if (Number.isFinite(n) && n >= 1 && n <= 3) return 'lower';
  return 'upper';
};

