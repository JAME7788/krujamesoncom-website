export interface LessonSignals {
  title: string;
  unit?: string;
  indicators?: string[];
  /** คำอธิบายกิจกรรม — สัญญาณอ่อนสุด เพราะมักมีคำทั่วไปอย่าง "ข้อมูล" ปนมา */
  activity?: string;
}

/**
 * จัดประเภทบทเรียนด้วยการให้คะแนนตามน้ำหนักของแหล่งข้อมูล ไม่ใช่เจอคำแรกแล้วจบ
 *
 * เดิมใช้วิธีเจอคำไหนก่อนชนะ ทำให้บทเรียน "การหารูปแบบของปัญหา และแยกย่อยเป็นส่วน ๆ"
 * ถูกจัดเป็นกลุ่มข้อมูล เพราะคำว่า "ข้อมูล" บังเอิญโผล่ในคำอธิบายกิจกรรม
 * ทั้งที่ชื่อเรื่องและชื่อหน่วยบอกชัดว่าเป็นเรื่องอัลกอริทึม
 */
const FIELD_WEIGHT = { title: 4, unit: 3, indicators: 2, activity: 1 } as const;

export const classifyLesson = (input: LessonSignals | string): LessonCategory => {
  const signals: LessonSignals = typeof input === 'string' ? { title: input } : input;
  const fields: Array<[keyof typeof FIELD_WEIGHT, string]> = [
    ['title', signals.title || ''],
    ['unit', signals.unit || ''],
    ['indicators', (signals.indicators || []).join(' ')],
    ['activity', signals.activity || ''],
  ];

  let best: LessonCategory | null = null;
  let bestScore = 0;

  // เรียงตาม CATEGORY_KEYWORDS ทำให้คะแนนเท่ากันแล้วกลุ่มที่มาก่อน (เช่น safety) ชนะ
  for (const [category, keywords] of CATEGORY_KEYWORDS) {
    let score = 0;
    for (const [field, text] of fields) {
      if (!text) continue;
      const haystack = text.toLowerCase();
      const hits = keywords.filter((word) => haystack.includes(word.toLowerCase())).length;
      score += hits * FIELD_WEIGHT[field];
    }
    if (score > bestScore) {
      bestScore = score;
      best = category;
    }
  }

  return best ?? 'algorithm';
};

