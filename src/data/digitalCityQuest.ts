export const DIGITAL_CITY_QUESTIONS: DigitalCityQuestion[] = MISSIONS.flatMap((mission) => (
  mission.questions.map((question, index) => ({
    ...question,
    id: `${mission.id}-${index + 1}`,
    missionId: mission.id,
    missionTitle: mission.title,
    domain: mission.domain,
    stage: (index + 1) as 1 | 2 | 3,
    stimulus: mission.stimulus,
    ...(mission.table ? { table: mission.table } : {}),
  }))
));

export const digitalCityQuestionId = (question: Pick<DigitalCityQuestion, 'missionId' | 'stage'> & { id?: string }) => (
  question.id || `${question.missionId}-${question.stage}`
);

export const shuffleDigitalCityQuestion = (
  question: DigitalCityQuestion,
  random: () => number = Math.random,
): DigitalCityQuestion => {
  const order = question.choices.map((_, index) => index);
  for (let index = order.length - 1; index > 0; index -= 1) {
    const swapWith = Math.floor(random() * (index + 1));
    [order[index], order[swapWith]] = [order[swapWith], order[index]];
  }
  return {
    ...question,
    choices: order.map((index) => question.choices[index]) as [string, string, string],
    answer: order.indexOf(question.answer),
  };
};

export const selectDigitalCityQuestion = (
  missionProgress: Record<string, number> = {},
  mastery: Partial<Record<LiteracyDomain, number>> = {},
  usedQuestionIds: string[] = [],
  random: () => number = Math.random,
): DigitalCityQuestion => {
  const usedIds = new Set(usedQuestionIds);
  const activeMissions = Object.entries(missionProgress)
    .filter(([, stage]) => stage > 0 && stage < 3);

  for (const [missionId, stage] of activeMissions) {
    const linked = DIGITAL_CITY_QUESTIONS.find((item) => (
      item.missionId === missionId
      && item.stage === stage + 1
      && !usedIds.has(digitalCityQuestionId(item))
    ));
    if (linked) return shuffleDigitalCityQuestion(linked, random);
  }

  const usedMissionIds = new Set(
    DIGITAL_CITY_QUESTIONS
      .filter((item) => usedIds.has(digitalCityQuestionId(item)))
      .map((item) => item.missionId),
  );
  const availableStarts = DIGITAL_CITY_QUESTIONS.filter((item) => (
    item.stage === 1
    && (missionProgress[item.missionId] || 0) === 0
    && !usedMissionIds.has(item.missionId)
    && !usedIds.has(digitalCityQuestionId(item))
  ));
  const weakestDomain = (Object.keys(LITERACY_DOMAINS) as LiteracyDomain[])
    .sort((left, right) => (mastery[left] || 0) - (mastery[right] || 0))[0];
  const weakestPool = availableStarts.filter((item) => item.domain === weakestDomain);
  const unseenQuestions = DIGITAL_CITY_QUESTIONS.filter((item) => !usedIds.has(digitalCityQuestionId(item)));
  const pool = weakestPool.length > 0
    ? weakestPool
    : availableStarts.length > 0
      ? availableStarts
      : unseenQuestions.length > 0
        ? unseenQuestions
        : DIGITAL_CITY_QUESTIONS;
  const selected = pool[Math.floor(random() * pool.length)] || DIGITAL_CITY_QUESTIONS[0];
  return shuffleDigitalCityQuestion(selected, random);
};

