export const getWorksheetTemplatesForClassroom = (
  classroom?: string,
  subject?: Subject,
): InteractiveWorksheetTemplate[] => {
  return INTERACTIVE_WORKSHEET_TEMPLATES.filter((tpl) => {
    if (classroom && classroom !== 'all' && tpl.classroom !== classroom) return false;
    if (subject && tpl.subject !== subject) return false;
    return true;
  });
};

export const getWorksheetTemplateById = (id?: string): InteractiveWorksheetTemplate | undefined =>
  id ? INTERACTIVE_WORKSHEET_TEMPLATES.find((t) => t.id === id) : undefined;
