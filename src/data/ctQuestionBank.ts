const answerIndex = (seed: string) => {
  let hash = 0;
  for (let index = 0; index < seed.length; index += 1) {
    hash = ((hash * 31) + seed.charCodeAt(index)) >>> 0;
  }
  return hash % 3;
};

const makeQuestion = (
  pillar: CTPillar,
  q: string,
  correct: string,
  distractors: [string, string],
  why: string,
): CTQuestion => {
  const unique = [correct, ...distractors].filter((choice, index, choices) => (
    choice.trim().length > 0 && choices.indexOf(choice) === index
  ));
  if (unique.length !== 3) {
    throw new Error(`Question choices must be unique: ${q}`);
  }
  const target = answerIndex(`${pillar}:${q}`);
  const choices = [...distractors];
  choices.splice(target, 0, correct);
  return { pillar, q, choices, answer: target, why };
};

