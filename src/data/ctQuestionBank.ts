const PILLARS: CTPillar[] = ['decompose', 'pattern', 'abstract', 'algorithm'];
const TIERS: AgeTier[] = ['lower', 'upper', 'middle'];

export const buildQuestionBank = (
  base: Record<AgeTier, CTQuestion[]>,
): Record<AgeTier, CTQuestion[]> => {
  const result = {} as Record<AgeTier, CTQuestion[]>;

  TIERS.forEach((tier) => {
    result[tier] = PILLARS.flatMap((pillar) => {
      const seen = new Set<string>();
      const merged = [
        ...base[tier].filter((question) => question.pillar === pillar),
        ...generatedQuestions[tier][pillar],
      ].filter((question) => {
        const key = question.q.trim().toLocaleLowerCase('th-TH');
        if (seen.has(key)) return false;
        seen.add(key);
        return true;
      });

      if (merged.length < QUESTIONS_PER_PILLAR) {
        throw new Error(`${tier}/${pillar} has only ${merged.length} unique questions`);
      }
      return merged.slice(0, QUESTIONS_PER_PILLAR);
    });
  });

  return result;
};

export const questionKey = (question: CTQuestion): string => (
  `${question.pillar}:${question.q.trim().toLocaleLowerCase('th-TH')}`
);

export const pickQuestionWithoutRecent = (
  pool: CTQuestion[],
  recentKeys: string[],
  pillar?: CTPillar,
  random: () => number = Math.random,
): { question: CTQuestion; recentKeys: string[] } => {
  const scoped = pillar ? pool.filter((question) => question.pillar === pillar) : pool;
  if (scoped.length === 0) {
    throw new Error(`No questions available${pillar ? ` for ${pillar}` : ''}`);
  }

  const recent = new Set(recentKeys);
  const fresh = scoped.filter((question) => !recent.has(questionKey(question)));
  const candidates = fresh.length > 0 ? fresh : scoped;
  const index = Math.min(candidates.length - 1, Math.floor(random() * candidates.length));
  const question = candidates[index];
  const limit = Math.min(60, Math.max(12, Math.floor(scoped.length * 0.6)));
  return {
    question,
    recentKeys: [...recentKeys, questionKey(question)].slice(-limit),
  };
};
