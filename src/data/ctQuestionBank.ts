const symbols = ['🔴', '🔵', '🟢', '🟡', '⭐', '🔺', '⬜', '🟣'];

const patternQuestions = (tier: AgeTier): CTQuestion[] => Array.from({ length: 100 }, (_, index) => {
  const mode = index % 5;
  const set = Math.floor(index / 5);

  if (mode === 0) {
    const start = (set % 10) + (tier === 'lower' ? 1 : 2);
    const step = Math.floor(set / 10) + (tier === 'middle' ? 3 : 1);
    const terms = Array.from({ length: 5 }, (_, offset) => start + (offset * step));
    const next = terms[4] + step;
    return makeQuestion(
      'pattern',
      `ลำดับ ${terms.join(', ')}, ... จำนวนถัดไปคือเท่าไร?`,
      String(next),
      [String(next + step), String(next - 1)],
      `จำนวนเพิ่มครั้งละ ${step} ดังนั้นจำนวนถัดไปคือ ${next}`,
    );
  }

  if (mode === 1) {
    const aIndex = Math.floor(set / (symbols.length - 1));
    const bOffset = set % (symbols.length - 1);
    const bIndex = bOffset >= aIndex ? bOffset + 1 : bOffset;
    const a = symbols[aIndex];
    const b = symbols[bIndex];
    let cIndex = (bIndex + 1) % symbols.length;
    if (cIndex === aIndex) cIndex = (cIndex + 1) % symbols.length;
    const c = symbols[cIndex];
    const cycle = tier === 'lower' ? [a, b] : [a, a, b, c];
    const shown = [...cycle, ...cycle, ...cycle.slice(0, Math.max(1, cycle.length - 1))];
    const next = cycle[(shown.length) % cycle.length];
    return makeQuestion(
      'pattern',
      `${shown.join(' ')} ... สัญลักษณ์ถัดไปคืออะไร?`,
      next,
      [next === a ? b : a, next === c ? b : c],
      `รูปแบบวนซ้ำเป็น ${cycle.join(' ')} จึงตามด้วย ${next}`,
    );
  }

  if (mode === 2) {
    const base = tier === 'middle' ? (set + 2) * 3 : set + 2;
    const step = tier === 'lower' ? 2 : (set % 4) + 2;
    const terms = [base, base + step, base + (2 * step), base + (3 * step), base + (4 * step)];
    const missing = terms[2];
    return makeQuestion(
      'pattern',
      `เติมจำนวนที่หายไป: ${terms[0]}, ${terms[1]}, __, ${terms[3]}, ${terms[4]}`,
      String(missing),
      [String(missing + step), String(missing - step)],
      `ลำดับเพิ่มครั้งละ ${step} จำนวนระหว่าง ${terms[1]} และ ${terms[3]} คือ ${missing}`,
    );
  }

  if (mode === 3) {
    const multiplier = tier === 'lower' ? 2 : (set % 2) + 2;
    const start = set + 1;
    const terms = Array.from({ length: 4 }, (_, offset) => start * (multiplier ** offset));
    return makeQuestion(
      'pattern',
      `กฎของลำดับ ${terms.join(', ')} คือข้อใด?`,
      `คูณ ${multiplier} ทุกครั้ง`,
      [`บวก ${multiplier} ทุกครั้ง`, `ลบ ${multiplier} ทุกครั้ง`],
      `แต่ละจำนวนเกิดจากจำนวนก่อนหน้าคูณ ${multiplier}`,
    );
  }

  const period = (set % 10) + 2;
  const targetOccurrence = Math.floor(set / 10) + (tier === 'middle' ? 4 : 3);
  const occurrence = period * (targetOccurrence - 1);
  return makeQuestion(
    'pattern',
    `กิจกรรมหนึ่งเกิดซ้ำทุก ${period} วัน หากวันนี้เป็นครั้งแรก จะเกิดอีกครั้งเป็นครั้งที่ ${targetOccurrence} ในอีกกี่วัน?`,
    String(occurrence),
    [String(occurrence + period), String(Math.max(period, occurrence - 1))],
    `เว้นช่วงครั้งละ ${period} วัน จึงนับช่วงซ้ำได้รวม ${occurrence} วัน`,
  );
});

